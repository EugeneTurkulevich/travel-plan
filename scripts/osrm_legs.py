def plan():
    if not ROUTE_PLAN:
        raise SystemExit("ROUTE_PLAN порожній — заповни його у scripts/osrm_legs.py")
    grand_km = grand_min = 0.0
    for day, date, pts in ROUTE_PLAN:
        km = mins = 0.0
        for a, b in zip(pts, pts[1:]):
            k, m = leg(a, b)
            km += k
            mins += m
        grand_km += km
        grand_min += mins
        chain = " → ".join(pts)
        print(f"D{day:<2} {date}  {km:>5.0f} км  {int(mins)//60}:{int(mins)%60:02d}   {chain}")
    print("-" * 78)
    print(f"РАЗОМ {grand_km:.0f} км, {int(grand_min)//60}:{int(grand_min)%60:02d} чистого руху "
          f"(без зупинок і буферів)")


